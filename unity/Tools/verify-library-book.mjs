// Run after Verify-Quest.ps1 -RenderImports, with the local Vite fixture server running.
import { chromium } from 'playwright-core';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
const output = path.resolve('.quest-evidence/book-library');
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const errors = [];
try {
  const page = await browser.newPage({ viewport: { width: 1024, height: 768 }, deviceScaleFactor: 2 });
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:5178/test-fixtures/browser/library-book.html');
  await page.getByRole('heading', { name: 'Animations', exact: true }).waitFor();
  await page.screenshot({ path: path.join(output, 'library-spread.png') });
  const overflow = await page.locator('.quest-library-page').evaluateAll(pages => pages.some(page => page.scrollWidth > page.clientWidth + 1));
  if (overflow) throw new Error('A library page overflows horizontally');
  await page.getByLabel('Search names and tags').fill('walk');
  await page.getByRole('button', { name: 'Search', exact: true }).click();
  await page.getByText('1–1 of 1', { exact: true }).waitFor();
  await page.getByRole('button', { name: /Everyday walk/ }).click();
  await page.getByLabel('Name', { exact: true }).fill('My daily walk');
  await page.getByRole('button', { name: 'Save details', exact: true }).click();
  await page.getByRole('heading', { name: 'My daily walk', exact: true }).waitFor();
  if (await page.locator('.quest-library-results button').count() !== 1) throw new Error('Filtered list changed after editing');
  await page.screenshot({ path: path.join(output, 'library-edited.png') });
  await page.getByRole('button', { name: 'Back to chat', exact: true }).click();
  await page.locator('.quest-library-spread').waitFor({ state: 'detached' });
  if (!await page.locator('.quest-chat-page').isVisible()) throw new Error('Chat did not return');
  await page.frameLocator('iframe').getByRole('button', { name: 'Try the phrase', exact: true }).waitFor({ timeout: 10000 });
  await page.frameLocator('iframe').getByRole('button', { name: 'Try the phrase', exact: true }).click();
  await page.frameLocator('iframe').getByText('Un café, por favor.', { exact: true }).waitFor();
  await page.screenshot({ path: path.join(output, 'returned-conversation.png') });
  await page.goto('http://127.0.0.1:5178/test-fixtures/browser/library-book.html?activity=1');
  await page.getByText('Tutor-state motions', { exact: true }).click();
  await page.getByRole('combobox', { name: 'Tutor state', exact: true }).selectOption('3');
  await page.getByRole('button', { name: 'Update state motion', exact: true }).waitFor();
  const assigned = page.getByRole('list', { name: 'Assigned state motions' });
  if (!await assigned.getByRole('button', { name: 'Greeting', exact: true }).isVisible()) throw new Error('Native state assignment is missing');
  if (await page.getByRole('combobox', { name: 'Selection weight', exact: true }).inputValue() !== '2' || await page.getByRole('combobox', { name: 'Seconds before reusing', exact: true }).inputValue() !== '2') throw new Error('Native state preferences were not restored');
  await page.screenshot({ path: path.join(output, 'activity-assignments.png') });
  await page.getByRole('button', { name: 'Undo assignments', exact: true }).scrollIntoViewIfNeeded();
  if (!await page.getByRole('button', { name: 'Undo assignments', exact: true }).isEnabled()) throw new Error('Assignment history is not available');
  if (await page.locator('.quest-library-page').evaluateAll(pages => pages.some(page => page.scrollWidth > page.clientWidth + 1))) throw new Error('State controls overflow the book');
  await page.screenshot({ path: path.join(output, 'activity-assignment-history.png') });
  await page.goto('http://127.0.0.1:5178/test-fixtures/browser/library-book.html?maintenance=1');
  await page.getByText('Usage and local storage', { exact: true }).click();
  await page.getByRole('button', { name: 'Remove local download', exact: true }).scrollIntoViewIfNeeded();
  if (!await page.getByRole('button', { name: 'Remove local download', exact: true }).isEnabled()) throw new Error('Native unreferenced download is not removable');
  await page.screenshot({ path: path.join(output, 'motion-maintenance.png') });
  await page.getByRole('button', { name: 'Remove local download', exact: true }).click();
  await page.getByRole('group', { name: 'Confirm download removal' }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(output, 'motion-removal-confirmation.png') });
  await page.getByRole('button', { name: 'Keep download', exact: true }).click();
  if (await page.getByRole('group', { name: 'Confirm download removal' }).count()) throw new Error('Download confirmation did not close');
  await page.goto('http://127.0.0.1:5178/test-fixtures/browser/library-book.html?removed=1');
  await page.getByText('Usage and local storage', { exact: true }).click();
  await page.getByRole('button', { name: 'Forget motion details', exact: true }).scrollIntoViewIfNeeded();
  if (!await page.getByRole('button', { name: 'Forget motion details', exact: true }).isEnabled()) throw new Error('An unused removed record cannot be forgotten');
  await page.getByRole('button', { name: 'Forget motion details', exact: true }).click();
  await page.getByRole('group', { name: 'Confirm forgetting motion' }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(output, 'motion-forget-confirmation.png') });
  await page.getByRole('button', { name: 'Keep details', exact: true }).click();
  await page.goto('http://127.0.0.1:5178/test-fixtures/browser/library-book.html?protected=1');
  await page.getByText('Usage and local storage', { exact: true }).click();
  await page.getByRole('list', { name: 'Motion uses' }).scrollIntoViewIfNeeded();
  if (await page.getByRole('button', { name: 'Remove local download', exact: true }).isEnabled()) throw new Error('Referenced native download must be protected');
  await page.screenshot({ path: path.join(output, 'motion-retained-references.png') });
  if (await page.locator('.quest-library-page').evaluateAll(pages => pages.some(page => page.scrollWidth > page.clientWidth + 1))) throw new Error('Library management overflows a book page');
  if (errors.length) throw new Error(errors.join('\n'));
  await writeFile(path.join(output, 'visual-check.json'), JSON.stringify({ viewport: '1024x768', scale: 2, overflow: false, search: 'passed', edit: 'passed', returnToChat: 'passed', artifactAfterReturn: 'passed', stateAssignmentValues: 'passed', stateAssignmentHistory: 'passed', removalConfirmation: 'passed', forgetConfirmation: 'passed', retainedReferences: 'passed', pageErrors: errors, scope: 'Native synthetic state; simulated fixture acknowledgements. Native operations tested separately in Unity.' }, null, 2));
  console.log('Library visual checks passed: search, metadata edit, return to chat state-assignment presentation and page bounds. '+output);
} finally { await browser.close(); }
